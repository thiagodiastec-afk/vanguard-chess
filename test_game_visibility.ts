import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { spectatorPreference, computerBroadcastPatch } from './src/lib/gameVisibility';
assert.equal(spectatorPreference(undefined), false);
assert.equal(spectatorPreference(false), false);
assert.equal(spectatorPreference(true), true);
assert.throws(() => spectatorPreference('false'));
const input = { sequence: 1, pgn: '', playerColor: 'w', difficulty: 'facil', ended: false };
const profile = { displayName: 'Alice', elo: 1200 };
const initial = computerBroadcastPatch(null,'alice',input,profile,1000)!;
assert.equal(initial.mode,'computer'); assert.equal(initial.whiteId,'alice'); assert.equal(initial.blackId,'computer');
assert.equal(initial.status,'playing'); assert.equal(initial.spectatorsAllowedWhite,true); assert.equal(initial.spectatorsAllowedBlack,true); assert.equal(initial.resultsRecorded,true);
assert.throws(()=>computerBroadcastPatch(initial,'bob',{...input, sequence:2},profile), /Sem acesso/);
assert.throws(()=>computerBroadcastPatch({...initial,mode:'online'},'alice',input,profile), /Sem acesso/);
assert.equal(computerBroadcastPatch(initial,'alice',input,profile),null,'duplicate must not roll back a snapshot');
const chess = new Chess(); chess.move('e4'); chess.move('e5');
const updated = computerBroadcastPatch(initial,'alice',{...input,sequence:2,pgn:chess.pgn()},profile)!;
assert.equal(updated.fen,chess.fen());
assert.equal(computerBroadcastPatch(updated,'alice',{...input,sequence:1},profile),null,'out-of-order snapshot ignored');
const closed=computerBroadcastPatch(updated,'alice',{...input,sequence:3,ended:true,pgn:chess.pgn()},profile)!;
assert.equal(closed.status,'abandoned');
assert.equal(computerBroadcastPatch(closed,'alice',{...input,sequence:4},profile),null,'closed sessions cannot reopen');
assert.throws(()=>computerBroadcastPatch(null,'alice',{...input,pgn:'illegal moves'},profile));
const mate=new Chess(); ['f3','e5','g4','Qh4#'].forEach(m=>mate.move(m));
assert.equal(computerBroadcastPatch(null,'alice',{...input,pgn:mate.pgn()},profile)!.status,'black_won');
assert.equal(computerBroadcastPatch(null,'alice',{...input,playerColor:'b'},profile)!.blackId,'alice');
console.log('GAME VISIBILITY: PASS (private default, validation, owner isolation, snapshots, ordering, closure, mate, colors)');
